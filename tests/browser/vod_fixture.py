"""Production VOD routes with synthetic media and deterministic inference only."""

from pathlib import Path
import os
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "vod-review"))

from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from backend import app as service
from backend.models import AudioTranscription, TranscriptionSegment

data = Path(os.environ["VOD_DATA_DIR"])
data.mkdir(parents=True, exist_ok=True)
media = data / "fixture.mp4"
if not media.exists():
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i", "color=c=red:s=128x96:d=12:r=10",
                    "-f", "lavfi", "-i", "sine=duration=12", "-c:v", "libx264", "-pix_fmt", "yuv420p",
                    "-c:a", "aac", "-shortest", str(media)], check=True, timeout=30)


class Classifier:
    """Replace the model boundary while real decoding, caching and persistence run."""

    device_label = "cpu"

    def predict_batch(self, crops):
        """Return a stable valid round label for each decoded crop."""
        return [("21", 0.95) for crop in crops]


def transcribe(path):
    """Replace Whisper inference while retaining real task/publication lifecycles."""
    return AudioTranscription(transcript="Fixture transcript — Café ☕", language="en",
                              segments=[TranscriptionSegment(start=1.25, end=3.5, text="Fixture transcript — Café ☕")])


service.get_ocr_classifier = lambda labels: Classifier()
service._transcribe_audio_file = transcribe
app = service.app


@app.get("/__test__/media")
def fixture_media():
    """Download generated bytes so the browser can perform a real file upload."""
    return FileResponse(media)


app.mount("/", StaticFiles(directory=ROOT / "vod-review/frontend/dist", html=True), name="built-frontend")
